"""Tests for the pinned dataset loader, schema validation, and integrity signal.

Positive tests load the committed ``data/raw/heart.csv``; negative tests drive
deliberately corrupted small fixtures (inline DataFrames plus a CSV generated by
mutating one cell of the real file) and assert the *named* exceptions fire with
actionable messages. No test touches the network: the download path is exercised
with a monkeypatched ``urlopen``.
"""

from __future__ import annotations

import urllib.error
from pathlib import Path

import pandas as pd
import pytest

from heart.data import load as load_module
from heart.data.load import (
    PINNED_SHA256,
    PINNED_SOURCE_URL,
    DownloadError,
    IntegrityChecksumError,
    SourceNotFoundError,
    load_dataset,
    main,
    raw_data_path,
    sha256_bytes,
    sha256_file,
)
from heart.data.schema import (
    ALL_COLUMNS,
    CATEGORICAL_LEVELS,
    EXPECTED_ROW_COUNT,
    FEATURE_COLUMNS,
    TARGET_COLUMN,
    DtypeMismatchError,
    MissingColumnsError,
    NullValueError,
    RowCountError,
    SchemaError,
    UnexpectedCategoryError,
    UnexpectedColumnsError,
    schema_report,
    validate_schema,
)

RAW = raw_data_path()


def valid_frame() -> pd.DataFrame:
    """A tiny frame that satisfies every declared column/level/dtype rule."""
    return pd.DataFrame(
        {
            "Age": [40, 49, 57],
            "Sex": ["M", "F", "F"],
            "ChestPainType": ["ATA", "NAP", "ATA"],
            "RestingBP": [140, 160, 130],
            "Cholesterol": [289, 180, 236],
            "FastingBS": [0, 0, 0],
            "RestingECG": ["Normal", "Normal", "LVH"],
            "MaxHR": [172, 156, 174],
            "ExerciseAngina": ["N", "N", "N"],
            "Oldpeak": [0.0, 1.0, 0.0],
            "ST_Slope": ["Up", "Flat", "Flat"],
            "HeartDisease": [0, 1, 1],
        }
    )


