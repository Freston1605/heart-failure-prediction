def test_valid_fixture_passes() -> None:
    validate_schema(valid_frame(), expected_rows=3)


def test_expected_rows_none_skips_row_check() -> None:
    validate_schema(valid_frame(), expected_rows=None)


def test_missing_columns_raise() -> None:
    frame = valid_frame().drop(columns=["Cholesterol"])
    with pytest.raises(MissingColumnsError) as excinfo:
        validate_schema(frame, expected_rows=3)
    assert "Cholesterol" in str(excinfo.value)


def test_unexpected_columns_raise() -> None:
    frame = valid_frame().assign(PatientID=[1, 2, 3])
    with pytest.raises(UnexpectedColumnsError) as excinfo:
        validate_schema(frame, expected_rows=3)
    assert "PatientID" in str(excinfo.value)


def test_row_count_mismatch_raises() -> None:
    with pytest.raises(RowCountError) as excinfo:
        validate_schema(valid_frame(), expected_rows=999)
    assert "999" in str(excinfo.value)


def test_dtype_mismatch_raises() -> None:
    frame = valid_frame().assign(Age=["40", "49", "57"])
    with pytest.raises(DtypeMismatchError) as excinfo:
        validate_schema(frame, expected_rows=3)
    message = str(excinfo.value)
    assert "Age" in message
    assert "integer" in message


def test_float_column_rejects_integer_storage() -> None:
    frame = valid_frame()
    frame["Oldpeak"] = [0, 1, 0]  # integer storage where a float is declared
    with pytest.raises(DtypeMismatchError) as excinfo:
        validate_schema(frame, expected_rows=3)
    assert "Oldpeak" in str(excinfo.value)


def test_null_values_raise() -> None:
    frame = valid_frame()
    frame["Cholesterol"] = frame["Cholesterol"].astype("Int64")
    frame.loc[0, "Cholesterol"] = pd.NA
    with pytest.raises(NullValueError) as excinfo:
        validate_schema(frame, expected_rows=3)
    assert "Cholesterol" in str(excinfo.value)


def test_unexpected_string_category_raises() -> None:
    frame = valid_frame()
    frame.loc[0, "Sex"] = "Q"
    with pytest.raises(UnexpectedCategoryError) as excinfo:
        validate_schema(frame, expected_rows=3)
    message = str(excinfo.value)
    assert "Sex" in message and "Q" in message and "F" in message and "M" in message


def test_unexpected_chestpain_category_raises() -> None:
    frame = valid_frame()
    frame.loc[0, "ChestPainType"] = "ZZZ"
    with pytest.raises(UnexpectedCategoryError) as excinfo:
        validate_schema(frame, expected_rows=3)
    assert "ChestPainType" in str(excinfo.value) and "ZZZ" in str(excinfo.value)


def test_non_binary_target_raises() -> None:
    frame = valid_frame()
    frame.loc[0, "HeartDisease"] = 2
    with pytest.raises(UnexpectedCategoryError) as excinfo:
        validate_schema(frame, expected_rows=3)
    assert "HeartDisease" in str(excinfo.value)


def test_non_dataframe_input_raises_schema_error() -> None:
    with pytest.raises(SchemaError):
        validate_schema([1, 2, 3], expected_rows=None)  # type: ignore[arg-type]


