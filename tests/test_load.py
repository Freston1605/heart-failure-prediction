def test_corrupted_csv_fixture_raises_named_exception(tmp_path: Path) -> None:
    frame = pd.read_csv(RAW)
    frame.loc[0, "ChestPainType"] = "ZZZ"  # inject an undeclared level
    bad_csv = tmp_path / "heart_bad_category.csv"
    frame.to_csv(bad_csv, index=False)

    with pytest.raises(UnexpectedCategoryError) as excinfo:
        load_dataset(path=bad_csv, verify_checksum=False, allow_download=False)
    message = str(excinfo.value)
    assert "ChestPainType" in message and "ZZZ" in message


