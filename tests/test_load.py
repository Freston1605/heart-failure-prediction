def test_checksum_mismatch_raises(tmp_path: Path) -> None:
    tampered = tmp_path / "heart.csv"
    tampered.write_bytes(RAW.read_bytes() + b"\n")  # same data, different bytes
    with pytest.raises(IntegrityChecksumError):
        load_dataset(path=tampered, allow_download=False)


def test_missing_source_without_download_raises(tmp_path: Path) -> None:
    with pytest.raises(SourceNotFoundError) as excinfo:
        load_dataset(path=tmp_path / "absent.csv", allow_download=False)
    assert "absent.csv" in str(excinfo.value)


class _FakeResponse:
    def __init__(self, payload: bytes) -> None:
        self._payload = payload

    def read(self) -> bytes:
        return self._payload

    def __enter__(self) -> "_FakeResponse":
        return self

    def __exit__(self, *exc: object) -> bool:
        return False


def test_download_writes_and_verifies(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    payload = RAW.read_bytes()
    monkeypatch.setattr(
        load_module.urllib.request, "urlopen", lambda *a, **k: _FakeResponse(payload)
    )
    dest = load_module.download_raw(
        tmp_path / "heart.csv", url=PINNED_SOURCE_URL, expected_sha256=PINNED_SHA256
    )
    assert dest.read_bytes() == payload
    assert not dest.with_name(dest.name + ".part").exists()


def test_download_rejects_checksum_mismatch(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    monkeypatch.setattr(
        load_module.urllib.request, "urlopen", lambda *a, **k: _FakeResponse(b"not the dataset")
    )
    dest = tmp_path / "heart.csv"
    with pytest.raises(IntegrityChecksumError):
        load_module.download_raw(dest, url=PINNED_SOURCE_URL, expected_sha256=PINNED_SHA256)
    assert not dest.exists()
    assert not dest.with_name(dest.name + ".part").exists()


def test_download_network_failure_raises_download_error(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    def _boom(*args: object, **kwargs: object) -> None:
        raise urllib.error.URLError("simulated connection loss")

    monkeypatch.setattr(load_module.urllib.request, "urlopen", _boom)
    with pytest.raises(DownloadError):
        load_module.download_raw(
            tmp_path / "heart.csv", url=PINNED_SOURCE_URL, expected_sha256=PINNED_SHA256
        )


