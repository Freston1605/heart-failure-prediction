def test_pinned_checksum_matches_committed_file() -> None:
    assert sha256_file(RAW) == PINNED_SHA256


def test_sha256_bytes_agrees_with_file_helper() -> None:
    assert sha256_bytes(RAW.read_bytes()) == sha256_file(RAW)


