def test_load_dataset_returns_validated_frame() -> None:
    dataset = load_dataset()
    assert dataset.row_count == EXPECTED_ROW_COUNT == 918
    assert dataset.columns == ALL_COLUMNS
    assert list(FEATURE_COLUMNS) == [c for c in ALL_COLUMNS if c != TARGET_COLUMN]
    # Schema validation already ran inside load_dataset; assert the surface.
    validate_schema(dataset.frame, expected_rows=EXPECTED_ROW_COUNT)


def test_load_dataset_reports_rows_dtypes_and_checksum() -> None:
    dataset = load_dataset()
    summary = dataset.summary()

    assert summary["row_count"] == 918
    assert summary["sha256"] == PINNED_SHA256
    assert summary["sha256_verified"] is True
    assert summary["target_column"] == "HeartDisease"
    assert set(summary["dtypes"]) == set(ALL_COLUMNS)

    rendered = dataset.describe()
    assert "sha256:" in rendered
    assert PINNED_SHA256 in rendered
    assert "rows: 918" in rendered
    # Every column's name and dtype is reported line by line.
    width = max(len(column) for column in ALL_COLUMNS)
    for column in ALL_COLUMNS:
        assert f"  {column:<{width}}  {summary['dtypes'][column]}" in rendered


def test_load_dataset_is_deterministic() -> None:
    first = load_dataset()
    second = load_dataset()
    pd.testing.assert_frame_equal(first.frame, second.frame)
    assert first.sha256 == second.sha256


def test_declared_levels_exactly_match_dataset() -> None:
    frame = pd.read_csv(RAW)
    for column, levels in CATEGORICAL_LEVELS.items():
        observed = {str(v) for v in frame[column].unique()}
        assert observed == set(levels), f"{column}: {observed} != {set(levels)}"


def test_schema_report_lists_every_column() -> None:
    report = schema_report()
    for column in ALL_COLUMNS:
        assert column in report
    assert str(EXPECTED_ROW_COUNT) in report


