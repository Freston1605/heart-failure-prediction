"""Report-parsing tests for reports/selection.md (S06/T03).

The durable artifact is regenerated by
``python -m heart.eval.selection``; this suite parses the committed file and
asserts the section contract the selection flow declares: winner line,
repeated-CV ranking, paired significance table, serving weight against the
budget, calibrated reliability-curve data with a Brier comparison, the chosen
threshold with its objective, named flags, and an explicit SHIP/NO-SHIP
verdict.
"""

from __future__ import annotations

import re
from pathlib import Path

import pytest

REPORT_PATH = Path("reports/selection.md")


@pytest.fixture(scope="module")
def report() -> str:
    if not REPORT_PATH.exists():
        pytest.skip("reports/selection.md not generated yet")
    return REPORT_PATH.read_text(encoding="utf-8")


def test_report_has_winner_line(report: str) -> None:
    match = re.search(r"Winner: \*\*(?P<name>[^*]+)\*\* \(roc_auc ", report)
    assert match, "missing the Winner line"
    assert match.group("name") == "random-forest"


def test_report_ranking_table_lists_both_candidates(report: str) -> None:
    assert "## Ranking" in report
    for name in ("random-forest", "logistic-regression-l2"):
        pattern = rf"\|\s*\d+\s*\|\s*{re.escape(name)}\s*\|"
        assert re.search(pattern, report), f"missing ranking row for {name}"


def test_report_paired_significance_table(report: str) -> None:
    assert "## Paired significance" in report
    assert "random-forest vs logistic-regression-l2" in report
    assert "p-value" in report
    assert "verdict" in report


def test_report_serving_weight_against_budget(report: str) -> None:
    match = re.search(
        r"Serving weight: \*\*(?P<mb>[\d.]+) MB\*\* \(budget (?P<budget>[\d.]+) MB\)",
        report,
    )
    assert match, "missing the serving-weight claim"
    assert float(match.group("budget")) > 0.0


def test_report_calibration_curve_and_brier_comparisoon(report: str) -> None:
    assert "Calibration (Brier " in report
    # Reliability-curve bins table with all three defined columns.
    assert "mean predicted" in report
    assert "fraction positive" in report
    assert "gap" in report
    # The calibrated curve must have at least one populated bin row.
    rows = [
        line
        for line in report.splitlines()
        if re.match(r"\|\s*\d+\s*\|\s*[\d.]+\s*\|\s*[\d.]+", line)
    ]
    assert rows, "calibration curve table has no populated bins"


def test_report_chosen_threshold_with_objective(report: str) -> None:
    match = re.search(
        r"Chosen threshold: \*\*(?P<t>[\d.]+)\*\* \(objective ``(?P<obj>\w+)``",
        report,
    )
    assert match, "missing the chosen-threshold line"
    assert 0.0 < float(match.group("t")) < 1.0
    assert match.group("obj") in ("f1", "balanced_accuracy", "youden_j")


def test_report_flags_and_explicit_verdict(report: str) -> None:
    assert "Flags:" in report
    match = re.search(r"\*\*Verdict: (SHIP|NO-SHIP)\*\*", report)
    assert match, "report must end with an explicit SHIP/NO-SHIP verdict"


def test_report_no_ship_carries_named_flags(report: str) -> None:
    """A NO-SHIP verdict must not be silent: named flags are required."""
    verdict = re.search(r"\*\*Verdict: (SHIP|NO-SHIP)\*\*", report)
    assert verdict
    if verdict.group(1) == "NO-SHIP":
        flags_line = next(line for line in report.splitlines() if "Flags:" in line)
        assert "none" not in flags_line, "NO-SHIP without named flags is silent"
