def test_empty_frame_raises_named_exception(tmp_path):
    """An empty fixture frame raises DataMethodsError with a named cause."""
    with pytest.raises(EmptyDatasetError) as excinfo:
        generate_report(
            pd.DataFrame(),
            output_dir=tmp_path / "never",
            report_path=tmp_path / "never.md",
        )
    assert isinstance(excinfo.value, DataMethodsError)
    assert "empty frame" in str(excinfo.value).lower()
    # No partial report (and no artifact file) is written on failure; the
    # artifact directory may exist but must be empty.
    assert not (tmp_path / "never.md").is_file()
    assert not any((tmp_path / "never").rglob("*"))


def test_missing_target_column_raises_named_exception(tmp_path):
    """A frame without the target column raises its named exception."""
    target_less = make_frame().drop(columns=["HeartDisease"])
    with pytest.raises(MissingTargetColumnError) as excinfo:
        generate_report(
            target_less,
            output_dir=tmp_path / "never",
            report_path=tmp_path / "never.md",
        )
    assert isinstance(excinfo.value, DataMethodsError)
    assert "HeartDisease" in str(excinfo.value)
    # No partial report (and no artifact file) is written on failure.
    assert not (tmp_path / "never.md").is_file()
    assert not any((tmp_path / "never").rglob("*"))
