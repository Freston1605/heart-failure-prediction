# ---------------------------------------------------------------------------
# Fixture frame (compact model of the raw dataset, mirrors T01/T02's fixture)
# ---------------------------------------------------------------------------


def make_frame(n: int = 120, seed: int = 42) -> pd.DataFrame:
    """Deterministic fixture frame in the raw dataset's column shape."""
    rng = np.random.default_rng(seed)
    severity = np.linspace(0.0, 1.0, n)
    cholesterol = rng.integers(120, 400, size=n)
    cholesterol[:4] = 0  # declared sentinels (zero-as-missing policy)
    restingbp = rng.integers(90, 190, size=n)
    restingbp[2] = 0  # declared sentinel
    return pd.DataFrame(
        {
            "Age": rng.integers(30, 81, size=n),
            "Sex": rng.choice(["M", "F"], size=n),
            "ChestPainType": rng.choice(["ASY", "ATA", "NAP", "TA"], size=n),
            "RestingBP": restingbp,
            "Cholesterol": cholesterol,
            "FastingBS": rng.integers(0, 2, size=n),
            "RestingECG": rng.choice(["Normal", "ST", "LVH"], size=n),
            "MaxHR": rng.integers(90, 202, size=n),
            "ExerciseAngina": np.where(rng.random(n) < severity, "Y", "N"),
            "Oldpeak": np.round(severity * 4.0, 2),
            "ST_Slope": rng.choice(["Up", "Flat", "Down"], size=n),
            "HeartDisease": np.where(rng.random(n) < severity, 1, 0),
        }
    )


# ---------------------------------------------------------------------------
# Report-side provenance probe (named helper, never a silent pass)
# ---------------------------------------------------------------------------


class ReportTamperingDetected(AssertionError):
    """Raised when stored report bytes cannot be reproduced by the generator.

    The artifact manifest hashes the *generated* artifacts; regeneration
    determinism (T02) hashes the *report* itself. A hand-edit to any number in
    the markdown diverges from a fresh regeneration, so comparing the stored
    bytes against freshly regenerated bytes is the tamper signal for the
    report side — and it must surface as this named exception, not a silent
    pass.
    """


def regenerate_and_compare(
    frame: pd.DataFrame, *, artifact_dir, companion_bytes: bytes, report_path
) -> object:
    """Re-render part A from code into ``artifact_dir`` and demand byte identity.

    The rendered report embeds its artifact-directory path, so regeneration
    must use the same artifact directory as the stored baseline: with the same
    provenance paths, byte-identity holds whenever the content is intact and
    fails the moment any number was hand-edited. This is the report-side
    provenance probe (the artifact manifest hashes generated artifacts;
    regeneration determinism hashes the report itself). Raises
    :class:`ReportTamperingDetected` on divergence — the T03(b) tamper-report
    negative path — never a silent pass.
    """
    fresh_report = generate_report(frame, output_dir=artifact_dir, report_path=report_path)
    fresh_bytes = fresh_report.read_bytes()
    if fresh_bytes != companion_bytes:
        first_divergence = next(
            (
                index
                for index, (left, right) in enumerate(
                    zip(companion_bytes, fresh_bytes)
                )
                if left != right
            ),
            min(len(companion_bytes), len(fresh_bytes)),
        )
        window = companion_bytes[max(0, first_divergence - 40): first_divergence + 40]
        raise ReportTamperingDetected(
            "regenerated report diverges from the stored companion bytes at "
            f"byte {first_divergence} (earliest divergence window: {window!r})"
        )
    return fresh_report


def cited_artifact_names(text: str) -> set[str]:
    """Extract every artifact basename the report cites (tables and figures)."""
    table_citations = [
        line.split("`")[1] for line in text.splitlines() if line.startswith("*Artifact:* `")
    ]
    figure_citations = [
        line.split("`")[1] for line in text.splitlines() if line.startswith("*Figure:* `")
    ]
    return set(table_citations + figure_citations)


@pytest.fixture()
def baseline(tmp_path):
    """Generate the untampered report + artifacts from the fixture."""
    report_path = generate_report(
        make_frame(),
        output_dir=tmp_path / "data-methods",
        report_path=tmp_path / "data-methods.md",
    )
    artifact_dir = tmp_path / "data-methods"
    manifest = json.loads((artifact_dir / "manifest.json").read_text(encoding="utf-8"))
    return {
        "report_path": report_path,
        "report_bytes": report_path.read_bytes(),
        "artifact_dir": artifact_dir,
        "manifest": manifest,
    }


# ---------------------------------------------------------------------------
# (a) Tamper-artifact negative test
# ---------------------------------------------------------------------------


def _tamper_one_byte(path) -> bytes:
    """Flip exactly one byte of the file (the last digit) and return the bytes."""
    data = bytearray(path.read_bytes())
    index = next(i for i in range(len(data) - 1, -1, -1) if data[i:i + 1].isdigit())
    replacement = b"0" if data[index:index + 1] != b"0" else b"1"
    data[index:index + 1] = replacement
    path.write_bytes(bytes(data))
    return path.read_bytes()


def test_tampered_table_artifact_raises_digest_mismatch(baseline, tmp_path):
    """One altered byte in a table artifact -> named tamper exception + regeneration detection."""
    artifact_dir = baseline["artifact_dir"]
    target = artifact_dir / "stage1_hygiene.json"
    original_bytes = target.read_bytes()
    assert verify_manifest(artifact_dir)  # intact baseline verifies clean

    tampered_bytes = _tamper_one_byte(target)
    assert tampered_bytes != original_bytes
    # The tampered frame is still well-formed JSON (a count digit was changed).
    payload = json.loads(tampered_bytes.decode("utf-8"))
    assert isinstance(payload, dict)

    with pytest.raises(ProvenanceDigestMismatchError) as excinfo:
        verify_manifest(artifact_dir)
    assert isinstance(excinfo.value, DataMethodsError)
    assert "stage1_hygiene.json" in str(excinfo.value)
    assert "digest mismatch" in str(excinfo.value)

    # The regeneration path detects the divergence: re-running the sanctioned
    # generator (same artifact directory, so the embedded provenance paths
    # match) produces bytes identical to the untouched baseline and does NOT
    # reproduce the tampered bytes.
    regenerate_and_compare(
        make_frame(),
        artifact_dir=artifact_dir,
        companion_bytes=baseline["report_bytes"],
        report_path=tmp_path / "regeneration.md",
    )
    regenerated = target.read_bytes()
    assert regenerated == original_bytes
    assert regenerated != tampered_bytes

    # The rebuilt directory verifies clean again: tampering is detected only
    # until the generator rewrites the artifact from code.
    assert verify_manifest(artifact_dir)


# ---------------------------------------------------------------------------
# (b) Tamper-report negative test
# ---------------------------------------------------------------------------


def _tamper_one_report_number(text: str) -> str:
    """Edit exactly one number in the rendered markdown (the stage-1 row count)."""
    pattern = re.compile(r"the raw frame is (\d+) rows")
    match = pattern.search(text)
    assert match is not None, "expected the hygiene row-count line in the report"
    row_count = int(match.group(1))
    return pattern.sub(f"the raw frame is {row_count - 1} rows", text, count=1)


def test_tampered_report_copy_is_flagged_by_regeneration(baseline, tmp_path):
    """A hand-edited number in a report copy is caught, not passed silently."""
    intact_text = baseline["report_bytes"].decode("utf-8")

    # Positive control: the untouched copy is exactly reproducible from code
    # (same artifact directory — same embedded provenance paths).
    regenerate_and_compare(
        make_frame(),
        artifact_dir=baseline["artifact_dir"],
        companion_bytes=intact_text.encode("utf-8"),
        report_path=tmp_path / "regeneration.md",
    )

    # Tamper: edit one number in a copy of the generated report markdown.
    tampered_text = _tamper_one_report_number(intact_text)
    assert tampered_text != intact_text
    tampered_bytes = tampered_text.encode("utf-8")

    with pytest.raises(ReportTamperingDetected):
        regenerate_and_compare(
            make_frame(),
            artifact_dir=baseline["artifact_dir"],
            companion_bytes=tampered_bytes,
            report_path=tmp_path / "regeneration.md",
        )


