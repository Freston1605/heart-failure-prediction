"""Provenance tamper tests and real-data end-to-end for the EDA report (M005/S01/T03).

M005's headline guarantee (decision D025) is that ``reports/data-methods.md``
part A is never hand-assembled and that *tampering with any number fails the
provenance test*. This module is the negative-path lock for that guarantee:

* tampering with one byte of a table artifact raises
  :class:`ProvenanceDigestMismatchError` from :func:`verify_manifest`, and the
  regeneration path detects the divergence (fresh code output cannot reproduce
  the tampered bytes),
* tampering with one number in a copy of the rendered report is flagged by the
  regeneration/comparison helper (:class:`ReportTamperingDetected`) instead of
  passing silently,
* the real committed dataset runs the full pipeline end-to-end: 918 rows,
  the declared sentinel-zero policy counts (``RestingBP`` 1, ``Cholesterol``
  172) appear in the report, every cited artifact exists, and the manifest
  verifies clean,
* empty frames and target-less frames fail with the named
  :class:`DataMethodsError`-family exceptions.

Matplotlib is forced to the headless Agg backend before the engine imports a
pyplot module (same guard as the other data-methods test modules), and every
write in this module lands under ``tmp_path`` — tests must never write into
the committed ``reports/`` tree.
"""

