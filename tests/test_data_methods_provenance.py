def test_real_dataset_end_to_end(tmp_path):
    """The committed 918-row dataset runs the full pipeline and verifies clean."""
    dataset = load_dataset(allow_download=False)
    assert dataset.sha256 == PINNED_SHA256

    frame = dataset.frame
    assert len(frame) == 918
    restingbp_zeros = int((frame["RestingBP"] == 0).sum())
    cholesterol_zeros = int((frame["Cholesterol"] == 0).sum())
    assert restingbp_zeros == 1
    assert cholesterol_zeros == 172

    report_path = generate_report(
        dataset,
        output_dir=tmp_path / "data-methods",
        report_path=tmp_path / "data-methods.md",
    )
    artifact_dir = tmp_path / "data-methods"
    text = report_path.read_text(encoding="utf-8")

    # Real 918-row-derived values appear in the rendered report.
    assert "918 rows" in text
    assert "matches the pinned digest (verified)" in text
    assert f"| `RestingBP` | {restingbp_zeros} |" in text
    assert f"| `Cholesterol` | {cholesterol_zeros} |" in text

    # Every cited artifact exists on disk under the artifact directory.
    cited = cited_artifact_names(text)
    assert len(cited) >= 5  # the four stage JSONs plus at least one figure
    for name in cited:
        assert (artifact_dir / name).is_file(), f"cited artifact missing: {name}"

    # The manifest covers every artifact and verifies clean.
    verified = verify_manifest(artifact_dir)
    for name in cited:
        if name != "manifest.json":
            assert name in verified, f"cited artifact unmanifested: {name}"
    assert verified["stage1_hygiene.json"]

    # Determinism on the real data: a re-run with the same output paths is
    # byte-identical (the embedded artifact-directory line makes the report
    # path-anchored, exactly like the fixture runs).
    rerun_report = generate_report(
        dataset,
        output_dir=tmp_path / "data-methods",
        report_path=tmp_path / "data-methods.md",
    )
    assert rerun_report.read_bytes() == report_path.read_bytes()


