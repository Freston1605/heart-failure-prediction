"""Model interpretability artifacts (S04/T04).

The package turns the leading S03 model into reviewable explanations of what it
learned on the S04/T03 selected feature representation:

* :mod:`heart.interpret.model` resolves the leading model, builds the selected
  pipeline, and exposes the two feature spaces;
* :mod:`heart.interpret.shap_export` produces per-feature SHAP summary values;
* :mod:`heart.interpret.coefficients` produces the coefficient / feature
  importance table;
* :mod:`heart.interpret.report` orchestrates both into
  ``reports/interpretability.md`` and its durable CSV artifacts.

``shap`` and ``mlflow`` are imported lazily inside the functions that need
them, so importing this package never requires the ``ml`` extra.
"""

